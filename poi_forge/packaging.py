def compute_sha256(file_path: Path | str, chunk_size: int = 1024 * 1024) -> str:
    """Compute SHA256 checksum of a file."""
    hasher = hashlib.sha256()
    with open(file_path, "rb") as f:
        while chunk := f.read(chunk_size):
            hasher.update(chunk)
    return hasher.hexdigest().lower()


def write_attribution_file(destination_dir: Path | str) -> Path:
    """Write ODbL ATTRIBUTION.txt into the destination directory."""
    dest = Path(destination_dir)
    dest.mkdir(parents=True, exist_ok=True)
    attr_file = dest / "ATTRIBUTION.txt"
    attr_file.write_text(ODBL_ATTRIBUTION_TEXT, encoding="utf-8")
    return attr_file


def create_category_meta(
    country_id: str,
    category_id: str,
    asc_files: list[Path],
    count: int,
    osm_extract_date: str | None = None,
) -> dict[str, Any]:
    """Create category metadata dictionary."""
    file_entries = []
    for f in asc_files:
        file_entries.append({
            "name": f.name,
            "bytes": f.stat().st_size,
            "sha256": compute_sha256(f),
        })

    now_iso = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    return {
        "country": country_id,
        "category": category_id,
        "count": count,
        "files": file_entries,
        "osm_extract_date": osm_extract_date or now_iso,
        "built_at": now_iso,
    }


def write_category_meta(
    category_dir: Path | str,
    meta_dict: dict[str, Any],
) -> Path:
    """Write meta.json inside category directory."""
    cat_path = Path(category_dir)
    cat_path.mkdir(parents=True, exist_ok=True)
    meta_file = cat_path / "meta.json"
    with open(meta_file, "w", encoding="utf-8") as f:
        json.dump(meta_dict, f, indent=2)
    return meta_file


def create_country_zip(
    country_dir: Path | str,
    output_zip: Path | str,
) -> Path:
    """Create a ZIP archive of a country package directory.

    Ensures ATTRIBUTION.txt and all category ASC and meta files are included.
    """
    country_path = Path(country_dir)
    zip_path = Path(output_zip)
    zip_path.parent.mkdir(parents=True, exist_ok=True)

    # Ensure attribution file exists in country_dir
    write_attribution_file(country_path)

    with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for p in sorted(country_path.rglob("*")):
            if p.is_file():
                rel_path = p.relative_to(country_path)
                zf.write(p, arcname=rel_path.as_posix())

    return zip_path
