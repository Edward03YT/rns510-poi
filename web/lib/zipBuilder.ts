/**
 * Builds a ZIP file containing the selected categories and ATTRIBUTION.txt in the browser.
 */
export async function buildBrowserZip(
  countryId: string,
  categories: CategoryEntry[],
  selectedCategoryIds: Set<string>,
  fileContentResolver?: (catId: string, fileName: string) => Promise<Uint8Array | string>
): Promise<Uint8Array> {
  const zipFiles: Record<string, Uint8Array> = {};

  // 1. Add ATTRIBUTION.txt in root
  zipFiles["ATTRIBUTION.txt"] = strToU8(ODBL_ATTRIBUTION_TEXT);

  // 2. Add category files
  for (const cat of categories) {
    if (!selectedCategoryIds.has(cat.id)) continue;

    for (const file of cat.files) {
      const zipPath = `${countryId}/${cat.id}/${file.name}`;

      if (fileContentResolver) {
        try {
          const content = await fileContentResolver(cat.id, file.name);
          zipFiles[zipPath] = typeof content === "string" ? strToU8(content) : content;
        } catch (err) {
          console.warn(`Failed to resolve content for ${file.name}, adding placeholder`, err);
          zipFiles[zipPath] = strToU8(`# Error fetching ${file.name}\r\n`);
        }
      } else {
        // Fallback synthetic content if no resolver is provided (offline or client demo)
        const sampleLine = `26.100000,44.400000,"${countryId} - ${cat.id} POI","Generated by rns510-poi-forge"\r\n`;
        zipFiles[zipPath] = strToU8(sampleLine);
      }
    }
  }

  // 3. Compress using fflate
  const zipped = zipSync(zipFiles, { level: 6 });
  return zipped;
}

/**
 * Trigger client-side file download in browser
 */
export function triggerBrowserDownload(data: Uint8Array | Blob | string, filename: string): void {
  const blob =
    data instanceof Blob
      ? data
      : new Blob([data as unknown as BlobPart], { type: "application/octet-stream" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
